#include "i18n/Lang.h"

#include <QHash>
#include <QSettings>

Lang *Lang::s_instance = nullptr;

Lang *Lang::instance()
{
    if (!s_instance) {
        s_instance = new Lang();
        // Remember the choice between runs.
        QSettings settings("HCMUS", "LibraryApp");
        s_instance->lang = static_cast<Language>(settings.value("language", English).toInt());
    }
    return s_instance;
}

Lang::Language Lang::language() const
{
    return lang;
}

void Lang::setLanguage(Language language)
{
    if (lang == language)
        return;
    lang = language;
    QSettings("HCMUS", "LibraryApp").setValue("language", static_cast<int>(language));
    emit languageChanged();
}

